import type { Metadata } from "next";
import { TransferDetailPage } from "@/features/transfers/transfers-page";
import { loadOrgContext } from "@/shared/org-context";

/** Rendered per request (session, entity). */
export const instant = false;

export const metadata: Metadata = { title: "Transfer details", robots: { index: false } };

export default async function Page({ params }: { params: Promise<{ org: string; id: string }> }) {
  const { org, id } = await params;
  const ctx = await loadOrgContext(org);
  return <TransferDetailPage ctx={ctx} id={id} />;
}
